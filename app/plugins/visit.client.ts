/**
 * Уведомление о визите: при каждом заходе на сайт (полной загрузке страницы)
 * дёргаем `POST /api/visit` — сервер отправляет письмо «Новый клиент: {IP}»
 * (см. server/api/visit.post.ts).
 *
 * Вызов отложен до onNuxtReady, чтобы не конкурировать с первым рендером.
 * Ошибка намеренно глотается — телеметрия не должна влиять на страницу.
 * SPA-переходы (router) не считаются: «заход» = новая загрузка страницы.
 */
export default defineNuxtPlugin(() => {
  onNuxtReady(() => {
    $fetch('/api/visit', { method: 'POST' }).catch(() => {})
  })
})